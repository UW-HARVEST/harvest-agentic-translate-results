#[test]
fn misc_internal_exports() {
    setup();
    // `_sodium_alloc_init` — idempotent, returns the same value in both
    let (c, r) = pair::<unsafe extern "C" fn() -> i32>("_sodium_alloc_init");
    for _ in 0..3 {
        let (a, b) = unsafe { (c(), r()) };
        eq_i32("_sodium_alloc_init", a, b);
    }
    // `_sodium_runtime_get_cpu_features` — no HAVE_* in this build, so the
    // `_cpuid` stub zero-fills and the function reports failure.
    let (c, r) = pair::<unsafe extern "C" fn() -> i32>("_sodium_runtime_get_cpu_features");
    for _ in 0..3 {
        let (a, b) = unsafe { (c(), r()) };
        eq_i32("_sodium_runtime_get_cpu_features", a, b);
    }
    // `sodium_crit_enter` / `sodium_crit_leave` — the no-op stubs (no
    // HAVE_PTHREAD / HAVE_ATOMIC_OPS), so enter returns 0 and leave returns 0
    // after an enter.
    let (ce, re) = pair::<unsafe extern "C" fn() -> i32>("sodium_crit_enter");
    let (cl, rl) = pair::<unsafe extern "C" fn() -> i32>("sodium_crit_leave");
    for _ in 0..3 {
        let (a, b) = unsafe { (ce(), re()) };
        eq_i32("sodium_crit_enter", a, b);
        let (a, b) = unsafe { (cl(), rl()) };
        eq_i32("sodium_crit_leave", a, b);
    }
}

/// `_crypto_sign_ed25519_detached` / `_verify_detached` — the internal forms
/// that take the extra `prehashed` flag, plus `_crypto_sign_ed25519_ref10_hinit`.
#[test]
fn internal_ed25519_sign_exports() {
    setup();
    let mut rng = Rng::new(0xAEA0);
    type IntDetached = unsafe extern "C" fn(*mut u8, *mut u64, *const u8, u64, *const u8, i32) -> i32;
    type IntVerify = unsafe extern "C" fn(*const u8, *const u8, u64, *const u8, i32) -> i32;
    type Hinit = unsafe extern "C" fn(*mut u8, i32) -> i32;

    let (ckp, rkp) = pair::<unsafe extern "C" fn(*mut u8, *mut u8) -> i32>("crypto_sign_ed25519_keypair");
    let (cd, rd) = pair::<IntDetached>("_crypto_sign_ed25519_detached");
    let (cv, rv) = pair::<IntVerify>("_crypto_sign_ed25519_verify_detached");

    for &mlen in &[0usize, 1, 31, 32, 33, 63, 64, 65, 127, 128, 1000] {
        // identical keypair on both sides
        let mut pk = [canary(32), canary(32)];
        let mut sk = [canary(64), canary(64)];
        for (w, f) in [ckp, rkp].into_iter().enumerate() {
            reset_rngs(0xF000 + mlen as u64);
            unsafe { f(pk[w].as_mut_ptr(), sk[w].as_mut_ptr()) };
        }
        eq_bytes("keypair pk", &pk[0], &pk[1]);
        eq_bytes("keypair sk", &sk[0], &sk[1]);

        let m = rng.bytes(mlen);
        // `prehashed = 0` is the only value reachable through the public
        // `crypto_sign_ed25519_detached`; `1` is the ed25519ph path (which
        // expects a 64-byte prehash), and any other int is an out-of-range enum
        // value that the C accepts across the FFI boundary.
        for &ph in &[0i32, 1, 2, -1, i32::MAX] {
            if ph == 1 && mlen != 64 {
                continue; // ed25519ph needs a 64-byte prehash
            }
            let mut sig = [canary(64), canary(64)];
            let mut sl = [0u64, 0u64];
            let mut rcs = [0i32; 2];
            for (w, f) in [cd, rd].into_iter().enumerate() {
                rcs[w] = unsafe {
                    f(
                        sig[w].as_mut_ptr(),
                        &mut sl[w],
                        m.as_ptr(),
                        mlen as u64,
                        sk[0].as_ptr(),
                        ph,
                    )
                };
            }
            eq_i32(&format!("_crypto_sign_ed25519_detached rc(ph={ph},m={mlen})"), rcs[0], rcs[1]);
            eq_usize("_crypto_sign_ed25519_detached *siglen", sl[0] as usize, sl[1] as usize);
            eq_bytes(&format!("_crypto_sign_ed25519_detached sig(ph={ph},m={mlen})"), &sig[0], &sig[1]);

            let mut vr = [0i32; 2];
            for (w, f) in [cv, rv].into_iter().enumerate() {
                vr[w] = unsafe { f(sig[0].as_ptr(), m.as_ptr(), mlen as u64, pk[0].as_ptr(), ph) };
            }
            eq_i32(&format!("_crypto_sign_ed25519_verify_detached rc(ph={ph})"), vr[0], vr[1]);

            // a corrupted signature must be rejected identically
            for i in [0usize, 31, 32, 63] {
                let mut bad = sig[0].clone();
                bad[i] ^= 0x01;
                let mut vr = [0i32; 2];
                for (w, f) in [cv, rv].into_iter().enumerate() {
                    vr[w] = unsafe { f(bad.as_ptr(), m.as_ptr(), mlen as u64, pk[0].as_ptr(), ph) };
                }
                eq_i32(
                    &format!("_crypto_sign_ed25519_verify_detached bad sig[{i}] (ph={ph})"),
                    vr[0],
                    vr[1],
                );
            }
        }
    }

    // `_crypto_sign_ed25519_ref10_hinit(state, prehashed)` over a sha512 state
    let (ch, rh) = pair::<Hinit>("_crypto_sign_ed25519_ref10_hinit");
    let sb = "crypto_hash_sha512_statebytes";
    type ShaUpdate = unsafe extern "C" fn(*mut u8, *const u8, u64) -> i32;
    type ShaFinal = unsafe extern "C" fn(*mut u8, *mut u8) -> i32;
    let (cu, ru) = pair::<ShaUpdate>("crypto_hash_sha512_update");
    let (cf, rf) = pair::<ShaFinal>("crypto_hash_sha512_final");
    for &ph in &[0i32, 1, 2, -1, i32::MAX] {
        let inp = rng.bytes(200);
        let mut out = [canary(64), canary(64)];
        let mut rcs = [0i32; 2];
        for (w, (h, u, f)) in [(ch, cu, cf), (rh, ru, rf)].into_iter().enumerate() {
            let mut st = State::for_sym(sb);
            unsafe {
                rcs[w] = h(st.as_mut_ptr(), ph);
                u(st.as_mut_ptr(), inp.as_ptr(), 200);
                f(st.as_mut_ptr(), out[w].as_mut_ptr());
            }
        }
        eq_i32(&format!("_crypto_sign_ed25519_ref10_hinit rc(ph={ph})"), rcs[0], rcs[1]);
        let (a, b) = (out[0].clone(), out[1].clone());
        eq_bytes(&format!("hinit digest (ph={ph})"), &a, &b);
    }
}
