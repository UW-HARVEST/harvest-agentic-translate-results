/// The 9 exported implementation v-tables are `D` (data) symbols in both
/// builds. The slot counts come from the C headers:
///
/// | v-table | slots |
/// |---|---|
/// | `aegis128l_soft_implementation` / `aegis256_soft_implementation` | 2 (`encrypt_detached`, `decrypt_detached`) |
/// | `crypto_onetimeauth_poly1305_donna_implementation` | 5 |
/// | `crypto_scalarmult_curve25519_ref10_implementation` | 2 (`mult`, `mult_base`) |
/// | `crypto_stream_chacha20_ref_implementation` | 4 |
/// | `crypto_stream_salsa20_ref_implementation` | 2 |
/// | `ipcrypt_soft_implementation` | 8 |
/// | `randombytes_{internal,sysrandom}_implementation` | 6 |
#[test]
fn exported_implementation_vtable_shapes() {
    setup();
    const VTABLES: &[(&str, usize)] = &[
        ("aegis128l_soft_implementation", 2),
        ("aegis256_soft_implementation", 2),
        ("crypto_onetimeauth_poly1305_donna_implementation", 5),
        ("crypto_scalarmult_curve25519_ref10_implementation", 2),
        ("crypto_stream_chacha20_ref_implementation", 4),
        ("crypto_stream_salsa20_ref_implementation", 2),
        ("ipcrypt_soft_implementation", 8),
        ("randombytes_internal_implementation", 6),
        ("randombytes_sysrandom_implementation", 6),
    ];
    for &(name, slots) in VTABLES {
        let c: *const *const std::ffi::c_void = sym(c_lib(), name);
        let r: *const *const std::ffi::c_void = sym(r_lib(), name);
        assert!(!c.is_null() && !r.is_null(), "{name} v-table is NULL");
        for i in 0..slots {
            let (a, b) = unsafe { (*c.add(i), *r.add(i)) };
            assert_eq!(
                a.is_null(),
                b.is_null(),
                "{name}: slot {i} nullness differs (C={a:?}, Rust={b:?})"
            );
        }
    }

    // the two randombytes v-tables expose an implementation_name() as slot 0
    for name in [
        "randombytes_internal_implementation",
        "randombytes_sysrandom_implementation",
    ] {
        let c: *const Option<unsafe extern "C" fn() -> *const std::ffi::c_char> = sym(c_lib(), name);
        let r: *const Option<unsafe extern "C" fn() -> *const std::ffi::c_char> = sym(r_lib(), name);
        unsafe {
            let (cf, rf) = (*c, *r);
            let (cf, rf) = (cf.expect("C name fn"), rf.expect("Rust name fn"));
            let (a, b) = (
                std::ffi::CStr::from_ptr(cf()).to_owned(),
                std::ffi::CStr::from_ptr(rf()).to_owned(),
            );
            assert_eq!(a, b, "{name}.implementation_name()");
        }
    }
}

