#!/usr/bin/env python3
"""Compute the whole-suite ERRORS.md coverage and stamp the check-marks.

Run AFTER `./check.sh` (every integration test is a separate process, and each one
appends the diagnostics it observed to `target/observed/<pid>.txt`).

    python3 tools/error_coverage.py            # report only
    python3 tools/error_coverage.py --stamp    # also update ERRORS.md check-marks

A site counts as covered only if some observed diagnostic *contains* its literal
message text: `png_chunk_*` prefix the message with the chunk name and
`png_formatted_warning` substitutes `@n` parameters, so containment is the right
relation.  The observed set is only ever appended to *after* `assert_same` /
`assert_same_forked` has already proved the two libraries agreed, so "covered"
means "both libraries produced this diagnostic, identically".
"""
import glob
import os
import re
import sys

SITES = 'tests/error_sites.txt'
OBSERVED = 'target/observed/*.txt'
OUT = 'ERROR_COVERAGE.md'

seen = set()
files = sorted(glob.glob(OBSERVED))
for f in files:
    with open(f, encoding='utf-8', errors='replace') as fh:
        for line in fh:
            line = line.rstrip('\n')
            if line:
                seen.add(line)

rows = []
for line in open(SITES, encoding='utf-8'):
    line = line.rstrip('\n')
    if not line:
        continue
    loc, kind, msg = line.split('|', 2)
    rows.append((loc, kind, msg))

covered, total, nolit = 0, 0, 0
report = []
by_file = {}
for loc, kind, msg in rows:
    f = loc.split(':')[0]
    st = by_file.setdefault(f, [0, 0])
    if not msg:
        nolit += 1
        report.append('| %s | `%s` | *(message built at run time)* | n/a |' % (loc, kind))
        continue
    total += 1
    st[1] += 1
    hit = any(msg in s for s in seen)
    if hit:
        covered += 1
        st[0] += 1
    report.append('| %s | `%s` | `%s` | %s |'
                  % (loc, kind, msg.replace('|', '\\|'), 'x' if hit else ' '))

pct = (covered * 100 // total) if total else 0
head = []
head.append('# ERROR_COVERAGE.md — which ERRORS.md rows the tests actually reached')
head.append('')
head.append('Generated by `tools/error_coverage.py` from `tests/error_sites.txt` (all')
head.append('%d diagnostic call sites in `c_src/src/*.c`) and `target/observed/*.txt`' % len(rows))
head.append('(every diagnostic the differential tests made **both** libraries emit).')
head.append('')
head.append('A site is marked `x` only if the suite observed its message coming out of')
head.append('both libraries with identical traces — `assert_same` / `assert_same_forked`')
head.append('compare *before* the message is recorded, so a recorded message is by')
head.append('construction one the two libraries agreed on.')
head.append('')
head.append('| | count |')
head.append('|---|---|')
head.append('| diagnostic call sites in the C sources | %d |' % len(rows))
head.append('| … with a literal message (checkable) | %d |' % total)
head.append('| … whose message is assembled at run time | %d |' % nolit)
head.append('| **sites reached by the differential tests** | **%d (%d%%)** |' % (covered, pct))
head.append('| distinct diagnostics observed | %d |' % len(seen))
head.append('| test processes that contributed | %d |' % len(files))
head.append('')
head.append('## Per source file')
head.append('')
head.append('| C file | reached | checkable |')
head.append('|--------|---------|-----------|')
for f in sorted(by_file):
    head.append('| `%s` | %d | %d |' % (f, by_file[f][0], by_file[f][1]))
head.append('')
head.append('## Every site')
head.append('')
head.append('| site | reporter | message | reached |')
head.append('|------|----------|---------|---------|')

unreached = [(loc, kind, msg) for loc, kind, msg in rows
             if msg and not any(msg in s for s in seen)]
tail = ['', '## Sites the suite did not reach (%d)' % len(unreached), '',
        'Each of these is either one of libpng\'s own internal consistency',
        'guards (the message says so: "internal error", "BAD internal error",',
        '"unexpected ...") or needs an object larger than 2 GiB / a 32-bit',
        '`size_t`, or is shadowed by an identical earlier test in the same',
        'function.  `tests/errors_deep.rs` documents the reasoning for each,',
        'next to the test that drives the nearest reachable neighbour.', '',
        '| site | reporter | message |', '|------|----------|---------|']
for loc, kind, msg in unreached:
    tail.append('| %s | `%s` | `%s` |' % (loc, kind, msg.replace('|', '\\|')))
open(OUT, 'w').write('\n'.join(head + report + tail) + '\n')
print('%s: %d/%d (%d%%) sites reached; %d distinct diagnostics from %d processes'
      % (OUT, covered, total, pct, len(seen), len(files)))

if '--stamp' in sys.argv:
    # Stamp the Part 1 rows of ERRORS.md: row D-N corresponds to line N of
    # tests/error_sites.txt (both are produced by the same scan, in order).
    text = open('ERRORS.md', encoding='utf-8').read()
    lines = text.split('\n')
    out = []
    n = 0
    for l in lines:
        m = re.match(r'^\| D-(\d+) \|(.*)\| \[[ x-]\] \|$', l)
        if m:
            i = int(m.group(1)) - 1
            if i < len(rows):
                loc, kind, msg = rows[i]
                if not msg:
                    # The message is assembled at run time (a variable, or
                    # png_formatted_warning parameters), so there is no literal to
                    # match: such a site cannot be checked off by text.
                    mark = '-'
                else:
                    mark = 'x' if any(msg in s for s in seen) else ' '
                l = '| D-%d |%s| [%s] |' % (i + 1, m.group(2), mark)
                n += 1
        out.append(l)
    open('ERRORS.md', 'w').write('\n'.join(out))
    print('stamped %d D-rows in ERRORS.md' % n)
