/* Structure for holding data about a particular state. */

#[repr(C)]
#[derive(Copy, Clone)]
pub struct stateblock {
    pub offset: c_int, /* Offset to opcode (-ve has meaning) */
    pub count: c_int,  /* Count for repeats */
    pub data: c_int,   /* Some use extra data */
}

pub const INTS_PER_STATEBLOCK: c_int = (size_of::<stateblock>() / size_of::<c_int>()) as c_int;

pub const OVEC_UNIT: usize = size_of::<PCRE2_SIZE>() / size_of::<c_int>();

pub const RWS_BASE_SIZE: usize = DFA_START_RWS_SIZE / size_of::<c_int>();
pub const RWS_RSIZE: usize = 1000;
pub const RWS_OVEC_RSIZE: usize = 1000 * OVEC_UNIT;
pub const RWS_OVEC_OSIZE: usize = 2 * OVEC_UNIT;

/* This structure is at the start of each workspace block. */

#[repr(C)]
#[derive(Copy, Clone)]
pub struct RWS_anchor {
    pub next: *mut RWS_anchor,
    pub size: u32, /* Number of ints */
    pub free: u32, /* Number of ints */
}

pub const RWS_ANCHOR_SIZE: usize = size_of::<RWS_anchor>() / size_of::<c_int>();
