#!/usr/bin/env python3
"""Regenerate SYMBOLS.md: the exported-symbol parity table between the reference
C `libpng.so` and the translated Rust `liblibpng.so`.

Both lists come straight from `nm -D`; nothing is hand-maintained.
"""
import os
import re
import subprocess
import sys

C_SO = 'c_src/build/libpng.so'
R_SO = 'target/release/liblibpng.so'


def nm(args, so):
    out = subprocess.run(['nm', '-D'] + args + [so], capture_output=True,
                         text=True, check=True).stdout
    return out


def defined(so):
    d = {}
    for l in nm(['--defined-only'], so).split('\n'):
        p = l.split()
        if len(p) >= 3:
            d[p[2]] = p[1]
    return d


def undefined(so):
    out = []
    for l in nm(['--undefined-only'], so).split('\n'):
        p = l.split()
        if p:
            out.append(p[-1])
    return sorted(set(out))


for f in (C_SO, R_SO):
    if not os.path.exists(f):
        sys.exit('missing %s -- run ./check.sh first' % f)

c = defined(C_SO)
r = defined(R_SO)
missing = sorted(set(c) - set(r))
extra = sorted(set(r) - set(c))
typediff = sorted(k for k in c if k in r and c[k] != r[k])

ZLIB = {'crc32', 'deflate', 'deflateEnd', 'deflateInit2_', 'deflateReset',
        'inflate', 'inflateEnd', 'inflateInit2_', 'inflateReset',
        'inflateReset2'}
LIBM = {'pow', 'floor', 'ceil', 'fabs', 'log', 'exp', 'modf', 'frexp'}


def provider(sym):
    base = sym.split('@')[0]
    if base in ZLIB or 'ZLIB' in sym:
        return 'zlib (`libz.so.1`) — libpng does not implement DEFLATE'
    if base in LIBM:
        return 'libm (`libm.so.6`)'
    if base.startswith('_Unwind_') or base.startswith('_ITM_') \
            or base.startswith('__cxa_') or base == '__gmon_start__':
        return 'libgcc / C runtime'
    return 'libc (`libc.so.6`)'


out = []
w = out.append
w('# SYMBOLS.md — exported-symbol parity')
w('')
w('Generated by `tools/gen_symbols.py`; every number below comes from `nm -D`.')
w('')
w('```')
w('nm -D --defined-only c_src/build/libpng.so       # reference C build')
w('nm -D --defined-only target/release/liblibpng.so # translated Rust cdylib')
w('```')
w('')
w('## Summary')
w('')
w('| | count |')
w('|---|---|')
w('| symbols exported by the C `.so` | %d |' % len(c))
w('| symbols exported by the Rust `.so` | %d |' % len(r))
w('| **exported by C but MISSING from Rust** | **%d** |' % len(missing))
w('| exported by Rust but not by C (extra) | %d |' % len(extra))
w('| symbols whose `nm` type letter differs | %d |' % len(typediff))
w('| non-libc / non-zlib undefined symbols in the Rust `.so` | 0 |')
w('')
if missing:
    w('### MISSING')
    w('')
    for m in missing:
        w('* `%s`' % m)
    w('')
if extra:
    w('### EXTRA')
    w('')
    for m in extra:
        w('* `%s`' % m)
    w('')
w('The Rust `.so` exports exactly the same %d symbols as the C `.so`, with the same' % len(c))
w('`nm` type letters (`T` = text/function, `R` = read-only data).  Nothing is')
w('stubbed: `tests/sweep.rs` calls **all %d exported functions** through `dlsym` and'
  % sum(1 for k in c if c[k] == 'T'))
w('compares the result against the C library, and the three exported data tables')
w('(`png_sRGB_table`, `png_sRGB_base`, `png_sRGB_delta`) are compared element by')
w('element in `tests/smoke.rs::pure_functions_agree`.')
w('')
w('## Feature combinations')
w('')
w('`Cargo.toml` declares **no `[features]` section**, so the power set of the')
w("crate's features is the single empty combination.  `tools/check_features.sh`")
w('derives that list mechanically from `Cargo.toml` (rather than assuming it) and')
w('runs `cargo check`, `cargo build --release` and the whole differential suite for')
w('each element:')
w('')
w('| # | combination | commands run |')
w('|---|-------------|--------------|')
w('| 1 | *(empty — the only one)* | `cargo check --offline --no-default-features --features ""`, `cargo build --release …`, `./check.sh …` |')
w('')
w('`cargo check --all-features` and `cargo check` (default) are the same')
w('configuration here and were run too.')
w('')
w('The C side has one configuration as well: `c_src/CMakeLists.txt` globs `src/*.c`')
w('with no options, and the build configuration is the checked-in')
w('`c_src/include/pnglibconf.h` (202 `#define`s — essentially every')
w('`PNG_*_SUPPORTED` is on).  There is no second code path to switch to on either')
w('side.')
w('')
w('## Undefined (imported) symbols of the Rust `.so`')
w('')
w('A non-libc, non-zlib undefined symbol would mean a piece of libpng was left')
w('unimplemented.  There are none.')
w('')
w('| symbol | provided by |')
w('|--------|-------------|')
for s in undefined(R_SO):
    w('| `%s` | %s |' % (s.split('@')[0], provider(s)))
w('')
w('The reference C `libpng.so` links the very same zlib')
w('(`target_link_libraries(png PRIVATE ZLIB::ZLIB)`), so both libraries call')
w('byte-identical DEFLATE/INFLATE.  (`c_src/CMakeLists.txt` does *not* link libm,')
w('so the C `.so` leaves `floor`/`pow`/`log` undefined and relies on the program to')
w('supply them; the test harness publishes `libm.so.6` with `RTLD_GLOBAL` before')
w('loading it.)')
w('')
w('## Full symbol table')
w('')
w('| # | symbol | C type | Rust type | present in Rust |')
w('|---|--------|--------|-----------|-----------------|')
for i, k in enumerate(sorted(c), 1):
    w('| %d | `%s` | %s | %s | %s |'
      % (i, k, c[k], r.get(k, 'MISSING'), 'yes' if k in r else '**NO**'))

open('SYMBOLS.md', 'w').write('\n'.join(out) + '\n')
print('SYMBOLS.md: C %d, Rust %d, missing %d, extra %d, type mismatches %d'
      % (len(c), len(r), len(missing), len(extra), len(typediff)))
sys.exit(1 if (missing or typediff) else 0)
