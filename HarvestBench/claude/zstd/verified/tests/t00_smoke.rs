//! Harness smoke test: both `.so`s load, agree on the trivial queries, and the
//! full exported-symbol set is reachable through `dlsym` on both sides.
mod common;
use common::*;

#[test]
fn both_libraries_load_and_agree_on_version() {
    let v = diff("ZSTD_versionNumber", |l| unsafe {
        l.sym::<FnVersionNumber>("ZSTD_versionNumber")()
    });
    assert_eq!(v, 10507);
    diff("ZSTD_versionString", |l| unsafe {
        cstr(l.sym::<FnVersionString>("ZSTD_versionString")())
    });
}

#[test]
fn clevel_range_matches() {
    diff("ZSTD_minCLevel", |l| unsafe {
        l.sym::<FnMinCLevel>("ZSTD_minCLevel")()
    });
    diff("ZSTD_maxCLevel", |l| unsafe {
        l.sym::<FnMaxCLevel>("ZSTD_maxCLevel")()
    });
    diff("ZSTD_defaultCLevel", |l| unsafe {
        l.sym::<FnDefaultCLevel>("ZSTD_defaultCLevel")()
    });
}

/// Every symbol the C `.so` exports must be resolvable via `dlsym` on the Rust
/// `.so` too. This is the run-time counterpart of the `nm -D` diff in
/// `SYMBOLS.md`: it proves the names are actually dynamically reachable, not
/// merely present in some section.
#[test]
fn every_c_export_is_dlsym_reachable_in_rust() {
    let p = pair();
    let names = c_exported_symbol_names();
    assert!(
        names.len() >= 600,
        "expected the full C export list, got {}",
        names.len()
    );
    let mut missing = Vec::new();
    for n in &names {
        if !p.r.has(n) {
            missing.push(n.clone());
        }
    }
    assert!(
        missing.is_empty(),
        "{} C symbols are not dlsym-reachable in the Rust .so:\n{}",
        missing.len(),
        missing.join("\n")
    );
    eprintln!("{} C exports all reachable in the Rust .so", names.len());
}

/// Read the C export list out of the `SYMBOLS.md` artifact produced in Phase A
/// (single source of truth, generated by `nm -D`).
fn c_exported_symbol_names() -> Vec<String> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("SYMBOLS.md");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let mut out = Vec::new();
    for line in text.lines() {
        // rows look like: | 12 | `ZSTD_compress` | `T` | ✔ |
        let cells: Vec<&str> = line.split('|').map(str::trim).collect();
        if cells.len() >= 5 && cells[1].parse::<u32>().is_ok() {
            let s = cells[2];
            if let Some(name) = s.strip_prefix('`').and_then(|s| s.strip_suffix('`')) {
                out.push(name.to_string());
            }
        }
    }
    out.sort();
    out.dedup();
    out
}

#[test]
fn one_shot_round_trip_is_byte_identical() {
    let src = corpus(Corpus::Text, 5000, 1);
    let cap = 4096 * 8;
    diff_bytes("ZSTD_compress lvl3", |l| compress_simple(l, &src, 3, cap));
    let frame = c_compress(&src, 3);
    diff_bytes("ZSTD_decompress", |l| {
        decompress_simple(l, &frame, src.len() + 16)
    });
}
