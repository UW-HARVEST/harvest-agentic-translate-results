#!/usr/bin/env python3
"""Regenerate ERRORS.md from the C sources.

Scans c_src/src/*.c for every rejection site: the js_*error()/js_error() throw
helpers, the lexer/parser/compiler error helpers, regexp.c's die(), js_throw()
re-raises and assert().  One ERRORS.md row per distinct (function, message
template) pair; the `sites` column lists every source line that raises it.
"""
import os
import re
import sys
from collections import OrderedDict

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "c_src", "src")

RAISE = re.compile(
    r"js_(?:typeerror|rangeerror|syntaxerror|referenceerror|urierror|evalerror|error)\(|"
    r"jsC_error\(|jsY_error\(|jsP_error\(|(?<![A-Za-z_])die\(|assert\(|js_throw\("
)
FUNC = re.compile(r"^([A-Za-z_][A-Za-z0-9_ \*]*?)([A-Za-z_][A-Za-z0-9_]*)\s*\(")

KIND = [
    ("js_typeerror(", "throws TypeError"),
    ("js_rangeerror(", "throws RangeError"),
    ("js_syntaxerror(", "throws SyntaxError"),
    ("js_referenceerror(", "throws ReferenceError"),
    ("js_urierror(", "throws URIError"),
    ("js_evalerror(", "throws EvalError"),
    ("jsY_error(", "throws SyntaxError (lexer)"),
    ("jsP_error(", "throws SyntaxError (parser)"),
    ("jsC_error(", "throws SyntaxError (compiler)"),
    ("js_error(", "throws Error"),
    ("js_throw(", "re-raises the pending exception value"),
    ("assert(", "assert() -> abort()"),
]


def kind_of(src):
    if re.search(r"(?<![A-Za-z_])die\(", src):
        return "js_regcomp -> NULL, *errorp = message"
    for needle, text in KIND:
        if needle in src:
            return text
    return "error"


def parse_triggers():
    """Read the Phase C trigger table out of tests/c_errors.rs.

    Returns {row_id: markdown cell describing how the row is covered}.
    """
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "tests", "c_errors.rs")
    if not os.path.exists(path):
        return {}
    txt = open(path).read()
    start = txt.find("static TRIGGERS")
    if start < 0:
        return {}
    end = txt.find("\n];", start)
    body = txt[start:end]
    # t(&[1, 2], Kind, "payload") — payload may span continuation lines with \
    entries = re.findall(
        r"t\(\s*&\[([0-9,\s]*)\]\s*,\s*([A-Za-z]+)\s*,\s*\"(.*?)\"\s*\)\s*,",
        body,
        re.S,
    )
    out = {}
    for ids, kind, payload in entries:
        payload = re.sub(r"\\\s*\n\s*", " ", payload)
        payload = payload.replace("|", "\\|").replace("`", "'")
        if kind == "Exempt":
            cell = f"`tests/c_errors.rs` — **not constructible**: {payload}"
        else:
            short = payload if len(payload) <= 110 else payload[:107] + "..."
            cell = f"`tests/c_errors.rs` `{kind}` `{short}`"
        for i in ids.split(","):
            i = i.strip()
            if i:
                out[int(i)] = cell
    return out


def main():
    rows = OrderedDict()
    for name in sorted(os.listdir(SRC)):
        if not name.endswith(".c"):
            continue
        cur = "<file scope>"
        with open(os.path.join(SRC, name)) as fh:
            for n, line in enumerate(fh, 1):
                stripped = line.rstrip("\n")
                if (
                    stripped
                    and not stripped[0].isspace()
                    and not stripped.startswith("#")
                    and "(" in stripped
                    and not stripped.rstrip().endswith(";")
                ):
                    m = FUNC.match(stripped)
                    if m:
                        cur = m.group(2)
                if not RAISE.search(stripped):
                    continue
                body = stripped.strip()
                msg = ""
                mm = re.search(r'"((?:[^"\\]|\\.)*)"', body)
                if mm:
                    msg = mm.group(1)
                key = (name, cur, msg, kind_of(body))
                rows.setdefault(key, {"lines": [], "src": body})["lines"].append(n)

    out = []
    out.append("# ERRORS.md — error / rejection surface of the C library\n")
    out.append(
        "Mechanically generated by `gen_errors.py` from `c_src/src/*.c`.  Every\n"
        "`js_error` / `js_typeerror` / `js_rangeerror` / `js_syntaxerror` /\n"
        "`js_referenceerror` / `js_urierror` / `js_evalerror` call, every lexer\n"
        "(`jsY_error`), parser (`jsP_error`) and compiler (`jsC_error`) error, every\n"
        "`die()` in the regexp compiler, every `js_throw()` re-raise and every\n"
        "`assert()` is listed.  One row per distinct (function, message template)\n"
        "pair; `sites` gives every source line that raises it.\n"
    )
    nsites = sum(len(v["lines"]) for v in rows.values())
    out.append(
        f"**{len(rows)} distinct rejections** across **{nsites}** source sites.\n"
    )
    out.append("How each class is observed from outside the `.so`:\n")
    out.append(
        "* JS-level throws — `js_dostring` / `js_ploadstring` / `js_pcall` /\n"
        "  `js_pconstruct` return non-zero and leave the error object on the stack;\n"
        "  `js_trystring(J,-1,...)` renders it as `\"<Type>: <message>\"`.\n"
        "* `die()` in `regexp.c` — `js_regcomp` returns `NULL` and stores the message\n"
        "  in `*errorp`.\n"
        "* `js_throw()` re-raise — the *pending* value propagates unchanged, so the\n"
        "  observable result is whatever value was thrown.\n"
        "* `assert()` — `abort()`; the trigger is outside the function's contract, so\n"
        "  it is verified by showing both libraries reject/avoid the same domain\n"
        "  rather than by calling it.\n"
    )
    out.append(
        "The `covered by` column is filled in from the Phase C trigger table in\n"
        "`tests/c_errors.rs` (parsed by `gen_errors.py`), so a row can never be\n"
        "silently left untested: `phase_c_coverage` fails if any row has no trigger,\n"
        "and `phase_c_triggers_hit_their_rows` fails if a trigger does not actually\n"
        "produce the message the row documents.\n"
    )
    triggers = parse_triggers()
    out.append("| # | function | trigger (the exact invalid input/condition) | expected C result | sites | covered by |")
    out.append("|---|----------|----------------------------------------------|-------------------|-------|------------|")
    for i, ((f, fn, msg, kind), v) in enumerate(rows.items(), 1):
        src = v["src"].replace("|", "\\|").replace("`", "\\`")
        m = msg.replace("|", "\\|") if msg else "(no literal message)"
        sites = ", ".join(f"{f}:{ln}" for ln in v["lines"])
        cov = triggers.get(i, "**NO TRIGGER**")
        out.append(f"| {i} | `{fn}` (`{f}`) | `{src}` | {kind} — message `{m}` | {sites} | {cov} |")
    text = "\n".join(out) + "\n"
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ERRORS.md")
    with open(dest, "w") as fh:
        fh.write(text)
    print(f"{len(rows)} rows, {nsites} sites -> {dest}")

    # Machine-readable index used by the Phase C coverage test.
    idx = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests", "errors_index.tsv")
    with open(idx, "w") as fh:
        fh.write("#id\tfile\tfunction\tmessage\tkind\n")
        for i, ((f, fn, msg, kind), v) in enumerate(rows.items(), 1):
            fh.write(f"{i}\t{f}\t{fn}\t{msg}\t{kind}\n")
    print(f"index -> {idx}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
