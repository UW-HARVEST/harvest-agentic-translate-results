use aes128_SIMD::aes;

#[test]
fn test_shift() {
    let mut state = [
        [0x00, 0x01, 0x02, 0x03],
        [0x10, 0x11, 0x12, 0x13],
        [0x20, 0x21, 0x22, 0x23],
        [0x30, 0x31, 0x32, 0x33],
    ];
    aes::shift(&mut state);
    assert_eq!(state, [
        [0x00, 0x01, 0x02, 0x03],
        [0x11, 0x12, 0x13, 0x10],
        [0x22, 0x23, 0x20, 0x21],
        [0x33, 0x30, 0x31, 0x32],
    ]);
}

#[test]
fn test_inv_shift_reverses_shift() {
    let original = [
        [0x00, 0x01, 0x02, 0x03],
        [0x10, 0x11, 0x12, 0x13],
        [0x20, 0x21, 0x22, 0x23],
        [0x30, 0x31, 0x32, 0x33],
    ];
    let mut state = original;
    aes::shift(&mut state);
    aes::inv_shift(&mut state);
    assert_eq!(state, original);
}

#[test]
fn test_shift_row0_unchanged() {
    let mut state = [
        [0xAA, 0xBB, 0xCC, 0xDD],
        [0x00, 0x00, 0x00, 0x00],
        [0x00, 0x00, 0x00, 0x00],
        [0x00, 0x00, 0x00, 0x00],
    ];
    aes::shift(&mut state);
    assert_eq!(state[0], [0xAA, 0xBB, 0xCC, 0xDD]);
}

