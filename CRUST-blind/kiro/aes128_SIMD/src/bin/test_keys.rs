use aes128_SIMD::keys;

#[test]
fn test_add() {
    let mut state = [
        [0x32, 0xf6, 0x30, 0x98],
        [0x43, 0xa8, 0x8d, 0xa2],
        [0x88, 0x31, 0x31, 0xe0],
        [0x5a, 0x31, 0x37, 0x07],
    ];
    let rk = [
        [0x2B, 0x15, 0xD2, 0x15],
        [0x7E, 0x16, 0xA6, 0x88],
        [0x28, 0xAE, 0xAB, 0x09],
        [0xF7, 0xCF, 0x4F, 0x3C],
    ];
    keys::add(&mut state, &rk);
    assert_eq!(state, [
        [0x19, 0xE3, 0xE2, 0x8D],
        [0x3D, 0xBE, 0x2B, 0x2A],
        [0xA0, 0x9F, 0x9A, 0xE9],
        [0xAD, 0xFE, 0x78, 0x3B],
    ]);
}

#[test]
fn test_add_double_is_identity() {
    let original = [
        [0x32, 0xf6, 0x30, 0x98],
        [0x43, 0xa8, 0x8d, 0xa2],
        [0x88, 0x31, 0x31, 0xe0],
        [0x5a, 0x31, 0x37, 0x07],
    ];
    let rk = [
        [0x2B, 0x15, 0xD2, 0x15],
        [0x7E, 0x16, 0xA6, 0x88],
        [0x28, 0xAE, 0xAB, 0x09],
        [0xF7, 0xCF, 0x4F, 0x3C],
    ];
    let mut state = original;
    keys::add(&mut state, &rk);
    keys::add(&mut state, &rk);
    assert_eq!(state, original);
}

