use aes128_SIMD::matrix::{columns, inv_columns};
use aes128_SIMD::aes::NB;

#[test]
fn test_columns() {
    let mut state: [[u8; NB]; 4] = [
        [0xDB, 0x13, 0x53, 0x45],
        [0xF2, 0x0A, 0x22, 0x5C],
        [0x01, 0x01, 0x01, 0x01],
        [0xC6, 0xC6, 0xC6, 0xC6],
    ];
    columns(&mut state);
    assert_eq!(state, [
        [0x67, 0xFF, 0x07, 0xA9],
        [0xE1, 0xC2, 0xD2, 0x38],
        [0x7A, 0x4A, 0x22, 0x4A],
        [0x12, 0xA9, 0x41, 0x05],
    ]);
}

#[test]
fn test_inv_columns() {
    let mut state: [[u8; NB]; 4] = [
        [0x67, 0xFF, 0x07, 0xA9],
        [0xE1, 0xC2, 0xD2, 0x38],
        [0x7A, 0x4A, 0x22, 0x4A],
        [0x12, 0xA9, 0x41, 0x05],
    ];
    inv_columns(&mut state);
    assert_eq!(state, [
        [0xDB, 0x13, 0x53, 0x45],
        [0xF2, 0x0A, 0x22, 0x5C],
        [0x01, 0x01, 0x01, 0x01],
        [0xC6, 0xC6, 0xC6, 0xC6],
    ]);
}

#[test]
fn test_columns_inv_columns_roundtrip() {
    let original: [[u8; NB]; 4] = [
        [0x01, 0x02, 0x03, 0x04],
        [0x05, 0x06, 0x07, 0x08],
        [0x09, 0x0A, 0x0B, 0x0C],
        [0x0D, 0x0E, 0x0F, 0x10],
    ];
    let mut state = original;
    columns(&mut state);
    inv_columns(&mut state);
    assert_eq!(state, original);
}

