use aes128_SIMD::cipher::{cipher, inv_cipher};
use aes128_SIMD::keys::expansion;
use aes128_SIMD::padding::{pad_buffer, remove_padding};
use aes128_SIMD::aes::{NB, NR, NK};

fn get_expanded_key() -> [u8; 4 * NB * (NR + 1)] {
    let key: [u8; 4 * NK] = [
        0x2B, 0x7E, 0x15, 0x16, 0x28, 0xAE, 0xD2, 0xA6,
        0xAB, 0xF7, 0x15, 0x88, 0x09, 0xCF, 0x4F, 0x3C,
    ];
    let mut w = [0u8; 4 * NB * (NR + 1)];
    expansion(&key, &mut w);
    w
}

#[test]
fn test_cipher() {
    let w = get_expanded_key();
    let plaintext: [u8; 16] = [
        0x32, 0x43, 0xF6, 0xA8, 0x88, 0x5A, 0x30, 0x8D,
        0x31, 0x31, 0x98, 0xA2, 0xE0, 0x37, 0x07, 0x34,
    ];
    let mut ct = [0u8; 16];
    cipher(&plaintext, &mut ct, &w);
    assert_eq!(ct, [
        0x67, 0xA5, 0x0A, 0x50, 0xAA, 0xE4, 0xF8, 0x41,
        0x09, 0x4A, 0xB3, 0xDE, 0x14, 0xFE, 0x79, 0xD7,
    ]);
}

#[test]
fn test_inv_cipher() {
    let w = get_expanded_key();
    let ct: [u8; 16] = [
        0x67, 0xA5, 0x0A, 0x50, 0xAA, 0xE4, 0xF8, 0x41,
        0x09, 0x4A, 0xB3, 0xDE, 0x14, 0xFE, 0x79, 0xD7,
    ];
    let mut pt = [0u8; 16];
    inv_cipher(&ct, &mut pt, &w);
    assert_eq!(pt, [
        0x32, 0x43, 0xF6, 0xA8, 0x88, 0x5A, 0x30, 0x8D,
        0x31, 0x31, 0x98, 0xA2, 0xE0, 0x37, 0x07, 0x34,
    ]);
}

#[test]
fn test_cipher_roundtrip_lorem() {
    let w = get_expanded_key();
    let plaintext = b"Lorem ipsum dolor sit amet, consectetur adipiscing elit. Sed do eiusmod tempor ...";
    let mut padded = Vec::new();
    let mut padded_len = 0;
    pad_buffer(plaintext, plaintext.len(), &mut padded, &mut padded_len);
    assert_eq!(padded_len, 96);

    let expected_ct: [u8; 96] = [
        0x75,0x48,0x76,0xEC,0x19,0x04,0x02,0xC6,0x98,0x38,0xCE,0x88,0x72,0x86,0xFD,0x2A,
        0x88,0x78,0x4C,0x43,0xE8,0xC2,0x18,0x90,0xB1,0x0C,0x1F,0x29,0xF0,0xBB,0xF1,0xF5,
        0xA9,0x08,0x7D,0x40,0x54,0x33,0x7A,0x1F,0xC2,0x30,0xB4,0x6D,0x9F,0xB7,0x42,0x4B,
        0xE8,0xB3,0xB7,0xEB,0x7A,0x86,0x89,0xAF,0xB7,0x13,0x53,0x8D,0x0A,0x2E,0xE5,0x2A,
        0x96,0x88,0x97,0x86,0xC6,0x9B,0x32,0x3D,0x45,0xB7,0x8C,0xDE,0xD3,0x1F,0x78,0xA8,
        0x3E,0xC4,0x74,0x48,0x9C,0xCF,0x28,0x5B,0x2D,0x94,0xD9,0x97,0x54,0x5F,0x0C,0x6C,
    ];

    // Encrypt block by block
    let mut ct = vec![0u8; padded_len];
    for i in (0..padded_len).step_by(16) {
        let in_block: [u8; 16] = padded[i..i+16].try_into().unwrap();
        let mut out_block = [0u8; 16];
        cipher(&in_block, &mut out_block, &w);
        ct[i..i+16].copy_from_slice(&out_block);
    }
    assert_eq!(ct.as_slice(), &expected_ct[..]);

    // Decrypt block by block
    let mut dt = vec![0u8; padded_len];
    for i in (0..padded_len).step_by(16) {
        let in_block: [u8; 16] = ct[i..i+16].try_into().unwrap();
        let mut out_block = [0u8; 16];
        inv_cipher(&in_block, &mut out_block, &w);
        dt[i..i+16].copy_from_slice(&out_block);
    }
    let unpadded_len = remove_padding(&dt, padded_len);
    assert_eq!(unpadded_len, 82);
    assert_eq!(&dt[..unpadded_len], plaintext);
}

