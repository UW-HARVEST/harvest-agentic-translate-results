use aes128_SIMD::aes::{shift, inv_shift, NB};

#[test]
fn test_shift() {
    let mut state: [[u8; NB]; 4] = [
        [0x00, 0x01, 0x02, 0x03],
        [0x10, 0x11, 0x12, 0x13],
        [0x20, 0x21, 0x22, 0x23],
        [0x30, 0x31, 0x32, 0x33],
    ];
    shift(&mut state);
    assert_eq!(state, [
        [0x00, 0x01, 0x02, 0x03],
        [0x11, 0x12, 0x13, 0x10],
        [0x22, 0x23, 0x20, 0x21],
        [0x33, 0x30, 0x31, 0x32],
    ]);
}

#[test]
fn test_inv_shift() {
    let mut state: [[u8; NB]; 4] = [
        [0x00, 0x01, 0x02, 0x03],
        [0x11, 0x12, 0x13, 0x10],
        [0x22, 0x23, 0x20, 0x21],
        [0x33, 0x30, 0x31, 0x32],
    ];
    inv_shift(&mut state);
    assert_eq!(state, [
        [0x00, 0x01, 0x02, 0x03],
        [0x10, 0x11, 0x12, 0x13],
        [0x20, 0x21, 0x22, 0x23],
        [0x30, 0x31, 0x32, 0x33],
    ]);
}

#[test]
fn test_shift_inv_shift_roundtrip() {
    let original: [[u8; NB]; 4] = [
        [0xAA, 0xBB, 0xCC, 0xDD],
        [0x11, 0x22, 0x33, 0x44],
        [0x55, 0x66, 0x77, 0x88],
        [0x99, 0x00, 0xEE, 0xFF],
    ];
    let mut state = original;
    shift(&mut state);
    inv_shift(&mut state);
    assert_eq!(state, original);
}

