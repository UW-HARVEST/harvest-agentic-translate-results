use aes128_SIMD::keys::{add, expansion};
use aes128_SIMD::aes::{NB, NR, NK};

#[test]
fn test_add() {
    let mut state: [[u8; NB]; 4] = [
        [0x32, 0x88, 0x31, 0xE0],
        [0x43, 0x5A, 0x31, 0x37],
        [0xF6, 0x30, 0x98, 0x07],
        [0xA8, 0x8D, 0xA2, 0x34],
    ];
    let rk: [[u8; NB]; 4] = [
        [0x2B, 0x28, 0xAB, 0x09],
        [0x7E, 0xAE, 0xF7, 0xCF],
        [0x15, 0xD2, 0x15, 0x4F],
        [0x16, 0xA6, 0x88, 0x3C],
    ];
    add(&mut state, &rk);
    assert_eq!(state, [
        [0x19, 0xA0, 0x9A, 0xE9],
        [0x3D, 0xF4, 0xC6, 0xF8],
        [0xE3, 0xE2, 0x8D, 0x48],
        [0xBE, 0x2B, 0x2A, 0x08],
    ]);
}

