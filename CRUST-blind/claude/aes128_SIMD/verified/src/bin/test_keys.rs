use aes128_SIMD::aes::{NB, NK, NR};
use aes128_SIMD::keys::{add, expansion};

#[test]
fn test_add() {
    let mut state: [[u8; 4]; 4] = [
        [0x00, 0x11, 0x22, 0x33],
        [0x44, 0x55, 0x66, 0x77],
        [0x88, 0x99, 0xaa, 0xbb],
        [0xcc, 0xdd, 0xee, 0xff],
    ];
    let rk: [[u8; 4]; 4] = [
        [0x01, 0x02, 0x03, 0x04],
        [0x05, 0x06, 0x07, 0x08],
        [0x09, 0x0a, 0x0b, 0x0c],
        [0x0d, 0x0e, 0x0f, 0x10],
    ];
    add(&mut state, &rk);
    let expected: [[u8; 4]; 4] = [
        [0x01, 0x13, 0x21, 0x37],
        [0x41, 0x53, 0x61, 0x7F],
        [0x81, 0x93, 0xA1, 0xB7],
        [0xC1, 0xD3, 0xE1, 0xEF],
    ];
    assert_eq!(state, expected);
}

#[test]
fn test_add_zero_round_key_no_change() {
    let original: [[u8; 4]; 4] = [
        [0x12, 0x34, 0x56, 0x78],
        [0x9a, 0xbc, 0xde, 0xf0],
        [0x01, 0x23, 0x45, 0x67],
        [0x89, 0xab, 0xcd, 0xef],
    ];
    let mut state = original;
    let rk = [[0u8; 4]; 4];
    add(&mut state, &rk);
    assert_eq!(state, original);
}

#[test]
fn test_add_inverse() {
    let original: [[u8; 4]; 4] = [
        [0x12, 0x34, 0x56, 0x78],
        [0x9a, 0xbc, 0xde, 0xf0],
        [0x01, 0x23, 0x45, 0x67],
        [0x89, 0xab, 0xcd, 0xef],
    ];
    let rk: [[u8; 4]; 4] = [
        [0x77, 0x88, 0x99, 0xaa],
        [0xbb, 0xcc, 0xdd, 0xee],
        [0x11, 0x22, 0x33, 0x44],
        [0x55, 0x66, 0x77, 0x88],
    ];
    let mut state = original;
    add(&mut state, &rk);
    add(&mut state, &rk);
    assert_eq!(state, original);
}

