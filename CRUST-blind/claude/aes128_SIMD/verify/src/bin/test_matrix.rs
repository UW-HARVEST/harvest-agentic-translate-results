use aes128_SIMD::matrix::{columns, inv_columns};

#[test]
fn test_columns() {
    let mut state: [[u8; 4]; 4] = [
        [0xd4, 0xe0, 0xb8, 0x1e],
        [0xbf, 0xb4, 0x41, 0x27],
        [0x5d, 0x52, 0x11, 0x98],
        [0x30, 0xae, 0xf1, 0xe5],
    ];
    columns(&mut state);
    let expected: [[u8; 4]; 4] = [
        [0x04, 0xE0, 0x48, 0x28],
        [0x66, 0xCB, 0xF8, 0x06],
        [0x81, 0x19, 0xD3, 0x26],
        [0xE5, 0x9A, 0x7A, 0x4C],
    ];
    assert_eq!(state, expected);
}

#[test]
fn test_inv_columns() {
    let mut state: [[u8; 4]; 4] = [
        [0x04, 0xe0, 0x48, 0x28],
        [0x66, 0xcb, 0xf8, 0x06],
        [0x81, 0x19, 0xd3, 0x26],
        [0xe5, 0x9a, 0x7a, 0x4c],
    ];
    inv_columns(&mut state);
    let expected: [[u8; 4]; 4] = [
        [0xD4, 0xE0, 0xB8, 0x1E],
        [0xBF, 0xB4, 0x41, 0x27],
        [0x5D, 0x52, 0x11, 0x98],
        [0x30, 0xAE, 0xF1, 0xE5],
    ];
    assert_eq!(state, expected);
}

#[test]
fn test_columns_roundtrip() {
    let original: [[u8; 4]; 4] = [
        [0x12, 0x34, 0x56, 0x78],
        [0x9a, 0xbc, 0xde, 0xf0],
        [0x01, 0x23, 0x45, 0x67],
        [0x89, 0xab, 0xcd, 0xef],
    ];
    let mut state = original;
    columns(&mut state);
    inv_columns(&mut state);
    assert_eq!(state, original);
}

#[test]
fn test_columns_zero() {
    let mut state = [[0u8; 4]; 4];
    columns(&mut state);
    assert_eq!(state, [[0u8; 4]; 4]);
}

#[test]
fn test_inv_columns_zero() {
    let mut state = [[0u8; 4]; 4];
    inv_columns(&mut state);
    assert_eq!(state, [[0u8; 4]; 4]);
}

