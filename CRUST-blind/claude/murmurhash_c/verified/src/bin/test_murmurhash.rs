#[test]
fn test_embedded_null_full() {
    // murmurhash("ab\0cd", 5, 0) -> 1668721715
    let key: &[u8] = &[b'a', b'b', 0u8, b'c', b'd'];
    assert_eq!(murmurhash(key, 0), 1668721715);
}

#[test]
fn test_embedded_null_partial() {
    // murmurhash("ab\0cd", 2, 0) i.e. just first two bytes "ab" -> 2613040991
    let key: &[u8] = &[b'a', b'b'];
    assert_eq!(murmurhash(key, 0), 2613040991);
}

#[test]
fn test_long_pangram_seed_zero() {
    // murmurhash("The quick brown fox jumps over the lazy dog", 43, 0) -> 776992547
    assert_eq!(
        murmurhash(b"The quick brown fox jumps over the lazy dog", 0),
        776992547
    );
}

#[test]
fn test_long_pangram_seed_1234() {
    // murmurhash("The quick brown fox jumps over the lazy dog", 43, 1234) -> 662953101
    assert_eq!(
        murmurhash(b"The quick brown fox jumps over the lazy dog", 1234),
        662953101
    );
}

#[test]
fn test_remainder_lengths_round_trip_consistency() {
    // Hashing the same key/seed should always produce identical output.
    let key = b"reproducibility";
    let h1 = murmurhash(key, 99);
    let h2 = murmurhash(key, 99);
    assert_eq!(h1, h2);
}

