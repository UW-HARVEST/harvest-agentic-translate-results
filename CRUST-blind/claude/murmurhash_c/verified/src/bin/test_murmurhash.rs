#[cfg(test)]
use murmurhash_c::murmurhash::{htole32, murmurhash, MURMURHASH_HAS_HTOLE32, MURMURHASH_VERSION};

#[test]
fn test_version_constant() {
    assert_eq!(MURMURHASH_VERSION, "0.2.0");
}

#[test]
fn test_has_htole32_constant() {
    assert_eq!(MURMURHASH_HAS_HTOLE32, 1);
}

#[test]
fn test_htole32_roundtrip() {
    // On little-endian machines htole32 is the identity.
    // The function is documented to perform the host-to-little-endian
    // conversion. Either way, the value preserved when the host is LE.
    assert_eq!(htole32(0), 0);
    assert_eq!(htole32(1), 1);
    assert_eq!(htole32(0xdeadbeef), 0xdeadbeef_u32.to_le());
    assert_eq!(htole32(0xffffffff), 0xffffffff_u32.to_le());
    assert_eq!(htole32(0x12345678), 0x12345678_u32.to_le());
}

