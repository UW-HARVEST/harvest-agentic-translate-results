use aes128_SIMD::cipher_utils;

#[test]
fn test_g_mult_basic() {
    // Verified via the C implementation
    assert_eq!(cipher_utils::g_mult(0x00, 0x00), 0x00);
    assert_eq!(cipher_utils::g_mult(0x01, 0x01), 0x01);
    assert_eq!(cipher_utils::g_mult(0x02, 0x01), 0x02);
    assert_eq!(cipher_utils::g_mult(0x03, 0x02), 0x06);
    // 0x57 * 0x83 = 0xC1 in GF(2^8) (canonical AES doc example)
    assert_eq!(cipher_utils::g_mult(0x57, 0x83), 0xC1);
    // 0x53 * 0xCA = 0x01 (multiplicative inverses in AES)
    assert_eq!(cipher_utils::g_mult(0x53, 0xCA), 0x01);
    // commutativity
    assert_eq!(cipher_utils::g_mult(0xab, 0xcd), cipher_utils::g_mult(0xcd, 0xab));
}

#[test]
fn test_g_mult_more() {
    // Spot checks computed from the canonical algorithm
    assert_eq!(cipher_utils::g_mult(0x02, 0x80), 0x1b);
    assert_eq!(cipher_utils::g_mult(0x03, 0xff), 0x1a);
    assert_eq!(cipher_utils::g_mult(0x0e, 0x53), 0x5f);
    // Additional values verified against the C `g_mult`:
    assert_eq!(cipher_utils::g_mult(0x09, 0xff), 0x46);
    assert_eq!(cipher_utils::g_mult(0x0b, 0x10), 0xb0);
    assert_eq!(cipher_utils::g_mult(0x0d, 0xab), 0x1e);
}

#[test]
fn test_sub() {
    let mut state: [[u8; 4]; 4] = [
        [0x00, 0x01, 0x02, 0x03],
        [0x10, 0x11, 0x12, 0x13],
        [0xff, 0xfe, 0xfd, 0xfc],
        [0x53, 0xed, 0x16, 0x63],
    ];
    cipher_utils::sub(&mut state);
    // SBOX values from aes.h
    assert_eq!(state[0], [0x63, 0x7c, 0x77, 0x7b]);
    assert_eq!(state[1], [0xca, 0x82, 0xc9, 0x7d]);
    assert_eq!(state[2], [0x16, 0xbb, 0x54, 0xb0]);
    assert_eq!(state[3], [0xed, 0x55, 0x47, 0xfb]);
}

#[test]
fn test_inv_sub() {
    let mut state: [[u8; 4]; 4] = [
        [0x63, 0x7c, 0x77, 0x7b],
        [0xca, 0x82, 0xc9, 0x7d],
        [0x16, 0xbb, 0x54, 0xb0],
        [0xed, 0x55, 0x47, 0xfb],
    ];
    cipher_utils::inv_sub(&mut state);
    assert_eq!(state[0], [0x00, 0x01, 0x02, 0x03]);
    assert_eq!(state[1], [0x10, 0x11, 0x12, 0x13]);
    assert_eq!(state[2], [0xff, 0xfe, 0xfd, 0xfc]);
    assert_eq!(state[3], [0x53, 0xed, 0x16, 0x63]);
}

#[test]
fn test_sub_inv_sub_roundtrip() {
    let original: [[u8; 4]; 4] = [
        [0xa1, 0xb2, 0xc3, 0xd4],
        [0xe5, 0xf6, 0x07, 0x18],
        [0x29, 0x3a, 0x4b, 0x5c],
        [0x6d, 0x7e, 0x8f, 0x90],
    ];
    let mut s = original;
    cipher_utils::sub(&mut s);
    cipher_utils::inv_sub(&mut s);
    assert_eq!(s, original);
}

