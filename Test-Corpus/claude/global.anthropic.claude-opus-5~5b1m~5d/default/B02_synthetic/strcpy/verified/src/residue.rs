//! `c_src/src/main.c` leaves `input_buffer` and `ref_buffer` uninitialised and
//! the library it calls runs `strlen`/`strcmp` over them, so whatever the
//! dynamic loader and the libc start-up code left on the stack becomes part of
//! the observable behaviour of the program.  Rust has no uninitialised memory,
