fn f10(h: u16) -> f32 {
    let n = (h >> 10) as usize;
    let idx = (h as usize & 0x3ff) + M_OFFSET[n] as usize;
    let bits = M_MANTISSA[idx].wrapping_add(M_EXPONENT[n]);
    f32::from_bits(bits)
}

// ---------------------------------------------------------------------------
// f11 / f12 / f13 - HSL/HSV color conversions
// ---------------------------------------------------------------------------

fn fabsf(x: f32) -> f32 {
    x.abs()
}

fn fmodf(a: f32, b: f32) -> f32 {
    a % b
}

fn floorf(x: f32) -> f32 {
    x.floor()
}

fn f11(dest: &mut [f32; 3], src: &[f32; 3]) {
    let h = src[0];
    let s = src[1];
    let l = src[2];
    if s == 0.0 {
        dest[0] = l;
        dest[1] = l;
        dest[2] = l;
        return;
    }
    let c = (1.0f32 - fabsf(2.0f32 * l - 1.0f32)) * s;
    let m = 1.0f32 * (l - 0.5f32 * c);
    let x = c * (1.0f32 - fabsf(fmodf(h / 60.0f32, 2.0f32) - 1.0f32));
    if h >= 0.0f32 && h < 60.0f32 {
        dest[0] = c + m;
        dest[1] = x + m;
        dest[2] = m;
    } else if h >= 60.0f32 && h < 120.0f32 {
        dest[0] = x + m;
        dest[1] = c + m;
        dest[2] = m;
    } else if h < 120.0f32 && h < 180.0f32 {
        // NOTE: bug in original C source preserved verbatim.
        dest[0] = m;
        dest[1] = c + m;
        dest[2] = x + m;
    } else if h >= 180.0f32 && h < 240.0f32 {
        dest[0] = m;
        dest[1] = x + m;
        dest[2] = c + m;
    } else if h >= 240.0f32 && h < 300.0f32 {
        dest[0] = x + m;
        dest[1] = m;
        dest[2] = c + m;
    } else if h >= 300.0f32 && h < 360.0f32 {
        dest[0] = c + m;
        dest[1] = m;
        dest[2] = x + m;
    } else {
        dest[0] = m;
        dest[1] = m;
        dest[2] = m;
    }
}

fn f12(dest: &mut [f32; 3], src: &[f32; 3]) {
    let r;
    let g;
    let b;
    let mut h = src[0];
    let s = src[1];
    let v = src[2];
    if s == 0.0 {
        dest[0] = v;
        dest[1] = v;
        dest[2] = v;
        return;
    }
    h /= 60.0f32;
    let i: c_int = floorf(h) as c_int;
    let f = h - i as f32;
    let p = v * (1.0f32 - s);
    let q = v * (1.0f32 - s * f);
    let t = v * (1.0f32 - s * (1.0f32 - f));
    match i {
        0 => {
            r = v;
            g = t;
            b = p;
        }
        1 => {
            r = q;
            g = v;
            b = p;
        }
        2 => {
            r = p;
            g = v;
            b = t;
        }
        3 => {
            r = p;
            g = q;
            b = v;
        }
        4 => {
            r = t;
            g = p;
            b = v;
        }
        _ => {
            r = v;
            g = p;
            b = q;
        }
    }
    dest[0] = r;
    dest[1] = g;
    dest[2] = b;
}

fn f13(dest: &mut [f32; 3], src: &[f32; 3]) {
    let r = src[0];
    let g = src[1];
    let b = src[2];
    let mut h: f32 = 0.0;
    let mut s: f32 = 0.0;
    let v: f32;
    let mut min = r;
    let mut max = r;
    let delta;
    min = if min < g { min } else { g };
    min = if min < b { min } else { b };
    max = if max > g { max } else { g };
    max = if max > b { max } else { b };
    delta = max - min;
    v = max;
    if delta == 0.0 || max == 0.0 {
        dest[0] = h;
        dest[1] = s;
        dest[2] = v;
        return;
    }
    s = delta / max;
    if r == max {
        h = (g - b) / delta;
    } else if g == max {
        h = 2.0 + (b - r) / delta;
    } else {
        h = 4.0 + (r - g) / delta;
    }
    h *= 60.0;
    if h < 0.0 {
        h += 360.0;
    }
    dest[0] = h;
    dest[1] = s;
    dest[2] = v;
}

