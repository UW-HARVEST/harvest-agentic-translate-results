// ---------------------------------------------------------------------------
// c2v / c2Circle / c2AABB / C2_TYPE
// ---------------------------------------------------------------------------

#[derive(Copy, Clone)]
struct c2v {
    x: f32,
    y: f32,
}

#[derive(Copy, Clone)]
struct c2Circle {
    p: c2v,
    r: f32,
}

#[derive(Copy, Clone)]
struct c2AABB {
    min: c2v,
    max: c2v,
}

#[derive(Copy, Clone, PartialEq, Eq)]
enum C2_TYPE {
    Circle = 0,
    AABB = 1,
}

fn c2V(x: f32, y: f32) -> c2v {
    c2v { x, y }
}

fn c2Maxv(a: c2v, b: c2v) -> c2v {
    c2V(
        if a.x > b.x { a.x } else { b.x },
        if a.y > b.y { a.y } else { b.y },
    )
}

fn c2Minv(a: c2v, b: c2v) -> c2v {
    c2V(
        if a.x < b.x { a.x } else { b.x },
        if a.y < b.y { a.y } else { b.y },
    )
}

fn c2Clampv(a: c2v, lo: c2v, hi: c2v) -> c2v {
    c2Maxv(lo, c2Minv(a, hi))
}

fn c2Sub(a: c2v, b: c2v) -> c2v {
    let mut a = a;
    a.x -= b.x;
    a.y -= b.y;
    a
}

fn c2Dot(a: c2v, b: c2v) -> f32 {
    a.x * b.x + a.y * b.y
}

fn c2CircletoCircle(A: c2Circle, B: c2Circle) -> c_int {
    let c = c2Sub(B.p, A.p);
    let d2 = c2Dot(c, c);
    let mut r2 = A.r + B.r;
    r2 = r2 * r2;
    (d2 < r2) as c_int
}

fn c2CircletoAABB(A: c2Circle, B: c2AABB) -> c_int {
    let L = c2Clampv(A.p, B.min, B.max);
    let ab = c2Sub(A.p, L);
    let d2 = c2Dot(ab, ab);
    let r2 = A.r * A.r;
    (d2 < r2) as c_int
}

fn c2AABBtoAABB(A: c2AABB, B: c2AABB) -> c_int {
    let d0 = (B.max.x < A.min.x) as c_int;
    let d1 = (A.max.x < B.min.x) as c_int;
    let d2 = (B.max.y < A.min.y) as c_int;
    let d3 = (A.max.y < B.min.y) as c_int;
    ((d0 | d1 | d2 | d3) == 0) as c_int
}

// f2 - dispatch helper. The original C uses void*; we replicate dispatch via
// an enum of references.
enum F2Shape<'a> {
    Circle(&'a c2Circle),
    AABB(&'a c2AABB),
}

fn f2(a: F2Shape, b: F2Shape) -> c_int {
    match a {
        F2Shape::Circle(ca) => match b {
            F2Shape::Circle(cb) => c2CircletoCircle(*ca, *cb),
            F2Shape::AABB(ab) => c2CircletoAABB(*ca, *ab),
        },
        F2Shape::AABB(aa) => match b {
            F2Shape::Circle(cb) => c2CircletoAABB(*cb, *aa),
            F2Shape::AABB(ab) => c2AABBtoAABB(*aa, *ab),
        },
    }
}

// ---------------------------------------------------------------------------
// f3 - signed integer division with custom remainder behavior. Uses wrapping
// arithmetic everywhere to match C semantics on overflow without panicking.
// ---------------------------------------------------------------------------

fn f3(v1: c_int, v2: c_int) -> c_int {
    if v2 == 0 {
        return 0;
    }
    const INT_MIN: c_int = -0x7fffffff - 1;
    let q: c_int;
    let r: c_int;
    if v1 >= 0 {
        if v2 >= 0 {
            return v1 / v2;
        } else if v2 != INT_MIN {
            q = (v1 / v2.wrapping_neg()).wrapping_neg();
            r = v1 % v2.wrapping_neg();
        } else {
            q = 0;
            r = v1;
        }
    } else if v1 != INT_MIN {
        if v2 >= 0 {
            q = (v1.wrapping_neg() / v2).wrapping_neg();
            r = (v1.wrapping_neg() % v2).wrapping_neg();
        } else if v2 != INT_MIN {
            q = v1.wrapping_neg() / v2.wrapping_neg();
            r = (v1.wrapping_neg() % v2.wrapping_neg()).wrapping_neg();
        } else {
            q = 1;
            r = v1.wrapping_sub(q.wrapping_mul(v2));
        }
    } else if v2 >= 0 {
        let s = v1.wrapping_add(v2).wrapping_neg();
        q = (s / v2).wrapping_neg().wrapping_sub(1);
        r = (s % v2).wrapping_neg();
    } else if v2 != INT_MIN {
        let s = v1.wrapping_sub(v2).wrapping_neg();
        let v2n = v2.wrapping_neg();
        q = (s / v2n).wrapping_add(1);
        r = (s % v2n).wrapping_neg();
    } else {
        q = 1;
        r = 0;
    }
    if r >= 0 {
        q
    } else {
        q.wrapping_add(if v2 > 0 { -1 } else { 1 })
    }
}

// ---------------------------------------------------------------------------
// cn_rnd_t / f4
// ---------------------------------------------------------------------------

#[derive(Copy, Clone)]
struct cn_rnd_t {
    state: [u64; 2],
}

fn cn_rnd_next(rnd: &mut cn_rnd_t) -> u64 {
    let mut x = rnd.state[0];
    let y = rnd.state[1];
    rnd.state[0] = y;
    x ^= x << 23;
    x ^= x >> 17;
    x ^= y ^ (y >> 26);
    rnd.state[1] = x;
    x.wrapping_add(y)
}

fn f4(rnd: &mut cn_rnd_t) -> f64 {
    let value = cn_rnd_next(rnd);
    let exponent: u64 = 1023;
    let mantissa = value >> 12;
    let result = (exponent << 52) | mantissa;
    f64::from_bits(result) - 1.0
}

// ---------------------------------------------------------------------------
// f5
// ---------------------------------------------------------------------------

fn f5(mut a: u32) -> u32 {
    a = ((a & 0xAAAA) >> 1) | ((a & 0x5555) << 1);
    a = ((a & 0xCCCC) >> 2) | ((a & 0x3333) << 2);
    a = ((a & 0xF0F0) >> 4) | ((a & 0x0F0F) << 4);
    a = ((a & 0xFF00) >> 8) | ((a & 0x00FF) << 8);
    a
}

// ---------------------------------------------------------------------------
// f7
// ---------------------------------------------------------------------------

fn f7(blocksize: u32, channels: u32, bitdepth: u32) -> u32 {
    let a = blocksize
        .wrapping_mul(bitdepth)
        .wrapping_mul(channels.wrapping_mul((channels != 2) as u32));
    let b = blocksize
        .wrapping_mul(bitdepth)
        .wrapping_mul((channels == 2) as u32);
    let c = blocksize
        .wrapping_mul(bitdepth.wrapping_add((bitdepth != 32) as u32))
        .wrapping_mul((channels == 2) as u32);
    18u32
        .wrapping_add(channels)
        .wrapping_add(
            a.wrapping_add(b).wrapping_add(c).wrapping_add(7) / 8,
        )
}

// ---------------------------------------------------------------------------
// lm_vec2 / f9
// ---------------------------------------------------------------------------

#[derive(Copy, Clone)]
struct lm_vec2 {
    x: f32,
    y: f32,
}

fn lm_v2(x: f32, y: f32) -> lm_vec2 {
    lm_vec2 { x, y }
}

fn lm_sub2(a: lm_vec2, b: lm_vec2) -> lm_vec2 {
    lm_v2(a.x - b.x, a.y - b.y)
}

fn lm_dot2(a: lm_vec2, b: lm_vec2) -> f32 {
    a.x * b.x + a.y * b.y
}

fn f9(p1: lm_vec2, p2: lm_vec2, p3: lm_vec2, p: lm_vec2) -> lm_vec2 {
    let v0 = lm_sub2(p3, p1);
    let v1 = lm_sub2(p2, p1);
    let v2 = lm_sub2(p, p1);
    let dot00 = lm_dot2(v0, v0);
    let dot01 = lm_dot2(v0, v1);
    let dot02 = lm_dot2(v0, v2);
    let dot11 = lm_dot2(v1, v1);
    let dot12 = lm_dot2(v1, v2);
    let invDenom = 1.0f32 / (dot00 * dot11 - dot01 * dot01);
    let u = (dot11 * dot02 - dot01 * dot12) * invDenom;
    let v = (dot00 * dot12 - dot01 * dot02) * invDenom;
    lm_v2(u, v)
}

