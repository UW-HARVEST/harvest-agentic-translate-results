//! Byte image of the readable pages of the *C* driver process.
//!
//! `stb_perlin_noise3_wrap_nonpow2` indexes `stb__perlin_randtab`,
//! `stb__perlin_randtab_grad_idx` and `basis` with values derived from its
//! `*_wrap` arguments, and those indices routinely fall outside the 512-entry
//! tables (see `ERRORS.md`). The C program therefore reads whatever the linker
//! happened to place next; because the driver is a **non-PIE** executable those
//! addresses are fixed, so the reads are reproducible.
//!
//! This is the image of the mapped range `[0x400000, 0x406000)` of
//! `c_src/build/driver`, reconstructed from its `PT_LOAD` segments the way the
//! kernel maps them:
//!
//! ```text
//!   0x400000..0x401000  <- file[0x0000..0x1000]   (R,  ELF header + dyn info)
//!   0x401000..0x403000  <- file[0x1000..0x3000]   (RX, .init/.plt/.text/.fini)
//!   0x403000..0x404000  <- file[0x3000..0x4000]   (R,  .rodata/.eh_frame)
//!   0x404000..0x405500  <- file[0x3000..0x4500]   (RW, .init_array .. data end)
//!   0x405500..0x406000  <- zero                   (padzero() of the .bss tail)
//! ```
//!
//! then corrected for the slots the dynamic linker writes before `main` runs
//! (see below). Reads outside the range are unmapped and the C process dies
//! with `SIGSEGV`; the boundaries were confirmed experimentally, randtab index
//! `4031` still prints a value while `4032` faults, and `-20544` still prints
//! while `-20545` faults.
//!
//! Every byte in the reachable index range `[-20544, 4032)` was verified
//! against the live C process (see `ERRORS.md`, "how the image was checked").
//!
//! # Bytes that cannot be reproduced
//!
//! Four slots hold pointers written at load time, and their middle bytes carry
//! ASLR entropy, which makes the C program's *output* random for the handful of
//! inputs that read them. Their low and high bytes are constant and are baked
//! in; the entropy-carrying bytes are left at zero. In `randtab` index terms
//! the unreproducible bytes are
//!
//! ```text
//!   -383..=-379   0x404ec1..=0x404ec5   .dynamic DT_DEBUG -> &_r_debug (ld.so)
//!   -118..=-116   0x404fca..=0x404fcc   .got     -> &__libc_start_main (libc)
//!    -79..=-76    0x404ff1..=0x404ff4   .got.plt[1] -> struct link_map *
//!    -71..=-68    0x404ff9..=0x404ffc   .got.plt[2] -> &_dl_runtime_resolve
//!    -54..=-52    0x40500a..=0x40500c   .got.plt -> resolved &__isoc99_scanf
//! ```

